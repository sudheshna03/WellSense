"""Dataset inspection for WellSense (Phase 1). Descriptive only: no model is trained here.

Usage:  python src/data/inspect_dataset.py [csv_path]
Outputs: results/dataset/dataset_inspection_report.md and figures in results/figures/.
"""
from __future__ import annotations

import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy.stats import fisher_exact

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_CSV = ROOT / "data" / "raw" / "student_mental_health.csv"
TARGET = "Do you have Depression?"
SOURCE = "Kaggle 'Student Mental Health' (shariful07), cited as ref [31] in the base paper"


def md_table(df: pd.DataFrame) -> str:
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(v) for v in r.values) + " |")
    return "\n".join(lines)


def normalise_labels(s: pd.Series) -> pd.Series:
    return s.astype(str).str.strip().str.lower()


def main(csv_path: Path) -> None:
    df = pd.read_csv(csv_path)
    n, p = df.shape
    fig_dir = ROOT / "results" / "figures"
    fig_dir.mkdir(parents=True, exist_ok=True)
    out = [f"# Dataset Inspection Report\n\nGenerated by `src/data/inspect_dataset.py` from the actual file.\n"]
    out.append(f"- **File:** `{csv_path.name}`\n- **Source:** {SOURCE}\n- **Rows:** {n}\n- **Columns:** {p}\n")

    # Schema
    schema = pd.DataFrame({"column": df.columns, "dtype": [str(t) for t in df.dtypes],
                           "missing": df.isna().sum().values, "unique": df.nunique().values})
    out.append("## Schema and missing values\n\n" + md_table(schema) + "\n")

    # Duplicates
    dup_all = int(df.duplicated().sum())
    dup_no_ts = int(df.drop(columns=["Timestamp"]).duplicated().sum())
    out.append(f"## Duplicates\n\n- Exact duplicate rows: {dup_all}\n- Duplicates ignoring Timestamp: {dup_no_ts}\n")

    # Target
    y = df[TARGET]
    vc = y.value_counts()
    out.append("## Target variable\n\n"
               f"Candidate target: `{TARGET}` (self-reported Yes/No).\n\n"
               + md_table(pd.DataFrame({"class": vc.index, "count": vc.values, "share": (vc.values / n).round(3)}))
               + f"\n\nMinority-class count: {int(vc.min())}. Majority-class baseline accuracy: {vc.max() / n:.3f}.\n")

    # Numerical
    out.append("## Numerical features\n\n" + md_table(df[["Age"]].describe().T.round(2).reset_index().rename(columns={"index": "feature"})) + "\n")
    ages = df["Age"].dropna()
    q1, q3 = ages.quantile([0.25, 0.75])
    iqr = q3 - q1
    n_out = int(((ages < q1 - 1.5 * iqr) | (ages > q3 + 1.5 * iqr)).sum())
    out.append(f"Age IQR outliers (1.5×IQR rule): {n_out}. Age range is {int(ages.min())}–{int(ages.max())} with no values 25–35 in this file.\n")

    # Categorical
    out.append("## Categorical features (raw values)\n")
    for c in df.columns:
        if c in ("Timestamp", "Age"):
            continue
        if df[c].nunique() > 12:
            raw, norm = df[c].nunique(), normalise_labels(df[c]).nunique()
            out.append(f"- **{c}**: {raw} raw categories, {norm} after trimming/lower-casing (free text; needs grouping).")
        else:
            out.append(f"- **{c}**: " + ", ".join(f"`{k}`={v}" for k, v in df[c].value_counts(dropna=False).items()))
    out.append("")
    cg_raw = df["What is your CGPA?"].value_counts()
    out.append(f"Label hygiene: CGPA has {len(cg_raw)} raw labels vs {df['What is your CGPA?'].str.strip().nunique()} after trimming (trailing space on '3.50 - 4.00'); "
               f"year of study has {df['Your current year of Study'].nunique()} raw labels vs {normalise_labels(df['Your current year of Study']).nunique()} after case-normalising.\n")

    # Association with target (descriptive; NOT a model)
    out.append("## Association of each binary feature with the target (descriptive)\n")
    rows = []
    for c in ["Marital status", "Do you have Anxiety?", "Do you have Panic attack?",
              "Did you seek any specialist for a treatment?", "Choose your gender"]:
        ct = pd.crosstab(df[c], y)
        pval = fisher_exact(ct.values)[1]
        rate = (df.assign(t=(y == "Yes").astype(int)).groupby(c)["t"].mean().round(2)).to_dict()
        rows.append({"feature": c, "depression rate by value": rate, "Fisher exact p": f"{pval:.2g}"})
    out.append(md_table(pd.DataFrame(rows)) + "\n")
    ms = pd.crosstab(df["Marital status"], y)
    tr = pd.crosstab(df["Did you seek any specialist for a treatment?"], y)
    out.append("Cross-tabs showing (near-)perfect separation:\n\n```\n" + ms.to_string() + "\n\n" + tr.to_string() + "\n```\n")

    # Leakage / privacy / relevance
    out.append("""## Possible target leakage and circularity (to be confirmed with the researcher)

| Feature | Concern | Proposed handling |
|---|---|---|
| `Did you seek any specialist for a treatment?` | Likely *downstream* of the condition (people seek treatment because they are depressed). In this file all 6 'Yes' are depressed. | Exclude from the primary feature set; keep only as a sensitivity analysis. |
| `Do you have Anxiety?`, `Do you have Panic attack?` | Other self-reported mental-health conditions that co-occur with depression; they are same-survey, same-respondent outcomes rather than independent risk factors. | Compare a *primary* set (without them) against an *extended* set (with them) and report both. |
| `Marital status` | All 16 'Yes' are depressed (16/16) — quasi-perfect separation. With n=101 this is most likely a small-sample artefact, not a reliable rule. | Keep, but flag; examine stability across repeated CV; do not interpret as causal. |
| `Timestamp` | Submission time of an online form; no legitimate predictive meaning. | Drop. |

## Features with privacy or fairness sensitivity

- `Choose your gender`, `Age`, `Marital status`: demographic; use only if justified and never display as a "cause".
- `What is your course?`: 41 distinct values after cleaning for 101 students — quasi-identifying and too sparse to learn from. Group coarsely (e.g. Engineering/IT, Islamic studies, Sciences/Health, Business/Law/Other) or drop.
- The mental-health fields are sensitive health data and are stored only locally in WellSense.
""")
    out.append("## Timestamp usefulness\n\nMixed date formats (e.g. `8/7/2020 12:02` and `13/07/2020 10:07:32`) are present, so the column is inconsistently formatted; it has no predictive meaning and is dropped.\n")

    # Figures
    fig, ax = plt.subplots(figsize=(4.5, 3.5))
    ax.bar(vc.index, vc.values, color=["#4C72B0", "#C44E52"][: len(vc)])
    for i, v in enumerate(vc.values):
        ax.text(i, v + 0.8, str(v), ha="center")
    ax.set(title="Target distribution: self-reported depression", ylabel="Students")
    fig.tight_layout(); fig.savefig(fig_dir / "target_distribution.png", dpi=150); plt.close(fig)

    miss = df.isna().sum()
    fig, ax = plt.subplots(figsize=(6, 3.5))
    ax.barh([c[:35] for c in miss.index], miss.values, color="#8172B2")
    ax.set(title="Missing values per column", xlabel="Count")
    fig.tight_layout(); fig.savefig(fig_dir / "missing_values.png", dpi=150); plt.close(fig)

    fig, ax = plt.subplots(figsize=(4.5, 3.5))
    ax.hist(ages, bins=range(18, 26), color="#55A868", edgecolor="white")
    ax.set(title="Age distribution", xlabel="Age", ylabel="Students")
    fig.tight_layout(); fig.savefig(fig_dir / "age_distribution.png", dpi=150); plt.close(fig)

    bin_cols = ["Marital status", "Do you have Depression?", "Do you have Anxiety?",
                "Do you have Panic attack?", "Did you seek any specialist for a treatment?"]
    enc = df[bin_cols].apply(lambda s: (s == "Yes").astype(int))
    enc["Female"] = (df["Choose your gender"] == "Female").astype(int)
    corr = enc.corr()  # phi coefficients for binary variables
    fig, ax = plt.subplots(figsize=(6.5, 5))
    im = ax.imshow(corr, cmap="coolwarm", vmin=-1, vmax=1)
    ax.set_xticks(range(len(corr))); ax.set_xticklabels([c[:18] for c in corr.columns], rotation=45, ha="right")
    ax.set_yticks(range(len(corr))); ax.set_yticklabels([c[:18] for c in corr.columns])
    for i in range(len(corr)):
        for j in range(len(corr)):
            ax.text(j, i, f"{corr.iloc[i, j]:.2f}", ha="center", va="center", fontsize=7)
    fig.colorbar(im); ax.set_title("Phi correlation of binary features")
    fig.tight_layout(); fig.savefig(fig_dir / "feature_correlation.png", dpi=150); plt.close(fig)
    out.append("## Figures\n\n`results/figures/`: target_distribution.png, missing_values.png, age_distribution.png, feature_correlation.png\n")

    # Sufficiency
    pos = int(vc.get("Yes", 0))
    out.append(f"""## Sufficiency for a deep-learning experiment

- {n} rows, {pos} positives, roughly 6–7 usable predictors (≈10–20 columns after one-hot encoding).
- A 20% hold-out would hold ≈{round(0.2 * n)} students and ≈{round(0.2 * pos)} positives; one prediction changes accuracy by ≈5 points, so a single test split is unreliable.
- Tabular data of this size generally does not favour deep networks over regularised linear/tree models. A compact MLP is feasible and honest to evaluate, but any claim that it beats other models would need repeated stratified cross-validation, confidence intervals and (ideally) nested CV for tuning.
- No sleep, study-habit, stress, activity, screen-time or social-support variables exist in this file.
""")
    path = ROOT / "results" / "dataset" / "dataset_inspection_report.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out), encoding="utf-8")
    print(f"Report written to {path}")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_CSV)
